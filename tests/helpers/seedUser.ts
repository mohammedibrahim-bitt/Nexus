import { getPayload } from 'payload'
import config from '../../src/payload.config.js'

export const testUser = {
  email: 'dev@payloadcms.com',
  password: 'test',
  // super_admin, not the tenant-scoped 'admin' — this user isn't assigned to
  // any tenant, and the multi-tenant plugin flatly denies a tenant-scoped
  // role with an empty `tenants` array rather than just filtering to
  // nothing. admin.e2e.spec.ts exercises basic admin-panel navigation
  // unrestricted by tenant, which is what super_admin is for.
  role: 'super_admin' as const,
}

/**
 * Seeds a test user for e2e admin tests.
 */
export async function seedTestUser(): Promise<void> {
  const payload = await getPayload({ config })

  // Delete existing test user if any
  await payload.delete({
    collection: 'users',
    where: {
      email: {
        equals: testUser.email,
      },
    },
  })

  // Create fresh test user
  await payload.create({
    collection: 'users',
    draft: false,
    data: testUser,
  })
}

/**
 * Cleans up test user after tests
 */
export async function cleanupTestUser(): Promise<void> {
  const payload = await getPayload({ config })

  await payload.delete({
    collection: 'users',
    where: {
      email: {
        equals: testUser.email,
      },
    },
  })
}
